namespace OCA\ArchiefMeta\Listener;

use OCA\ArchiefMeta\AppInfo\Application;
use OCA\Files\Event\LoadAdditionalScriptsEvent;
use OCP\EventDispatcher\Event;
use OCP\EventDispatcher\IEventListener;
use OCP\Util;

/**
 * Adds the sidebar tab script to the Files app.
 *
 * @template-implements IEventListener<Event>
 */
class LoadSidebarScript implements IEventListener {
	#[\Override]
	public function handle(Event $event): void {
		if (!$event instanceof LoadAdditionalScriptsEvent) {
			return;
		}
		Util::addInitScript(Application::APP_ID, 'archiefmeta-sidebar');
	}
}
